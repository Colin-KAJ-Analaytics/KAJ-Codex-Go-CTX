package scanner

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestGeneratedDetection(t *testing.T) {
	if !ReaderHasGeneratedHeader(strings.NewReader("// Code generated by x. DO NOT EDIT.\npackage p\n")) {
		t.Fatal("expected generated header")
	}
	got := Classify(t.TempDir(), "internal/api/user.pb.go", 10)
	if got.Kind != KindGenerated || !got.IgnoredByDefault {
		t.Fatalf("expected generated ignored file, got %#v", got)
	}
}

func TestIgnoredDirectoryDetection(t *testing.T) {
	root := t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, "vendor", "x"), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "vendor", "x", "x.go"), []byte("package x\n"), 0644); err != nil {
		t.Fatal(err)
	}
	res, err := Scan(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Files) != 1 || !res.Files[0].IgnoredByDefault || res.Files[0].Kind != KindVendor {
		t.Fatalf("expected ignored vendor dir, got %#v", res.Files)
	}
}

func TestNormalGoSourceClassification(t *testing.T) {
	got := Classify(t.TempDir(), "internal/auth/auth.go", 42)
	if got.Kind != KindGoSource || got.IgnoredByDefault {
		t.Fatalf("expected normal Go source, got %#v", got)
	}
}
